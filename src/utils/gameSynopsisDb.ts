/**
 * Searches the local custom synopsis DB and the built-in DB library for a matching title.
 */
export function findSynopsisInDb(
  gameTitle: string,
  customDb?: CustomSynopsisEntry[]
): CustomSynopsisEntry | undefined {
  if (!gameTitle) return undefined;
  const cleanTitle = gameTitle.toLowerCase().trim();

  // 1. Check user custom DB first
  if (customDb && customDb.length > 0) {
    const directMatch = customDb.find(
      (e) => e?.gameTitle && e.gameTitle.toLowerCase().trim() === cleanTitle
    );
    if (directMatch) return directMatch;

    const fuzzyMatch = customDb.find(
      (e) =>
        e?.gameTitle &&
        (cleanTitle.includes(e.gameTitle.toLowerCase().trim()) ||
          e.gameTitle.toLowerCase().trim().includes(cleanTitle))
    );
    if (fuzzyMatch) return fuzzyMatch;
  }

  // 2. Check built-in synopsis database
  const builtInDirect = BUILT_IN_GAME_SYNOPSES.find(
    (e) => e?.gameTitle && e.gameTitle.toLowerCase().trim() === cleanTitle
  );
  if (builtInDirect) return builtInDirect;

  const builtInFuzzy = BUILT_IN_GAME_SYNOPSES.find((e) => {
    if (!e?.gameTitle) return false;
    const eTitle = e.gameTitle.toLowerCase().trim();
    return cleanTitle.includes(eTitle) || eTitle.includes(cleanTitle);
  });
  if (builtInFuzzy) return builtInFuzzy;

  return undefined;
}
